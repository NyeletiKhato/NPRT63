-- Apply to an existing Supabase project before the read-only digital cleanup.
begin;
alter table public.users add column if not exists admin_mfa_secret text;
alter table public.users add column if not exists admin_mfa_enabled boolean not null default false;

create table if not exists public.app_sessions (
  sid text primary key,
  session_data jsonb not null,
  expires_at timestamptz not null
);
create index if not exists app_sessions_expires_at on public.app_sessions(expires_at);
create table if not exists public.security_rate_limits (
  bucket text primary key,
  window_started_at timestamptz not null,
  attempts integer not null default 0
);
create table if not exists public.security_audit_logs (
  id bigint generated by default as identity primary key,
  actor_user_id bigint,
  event text not null,
  target_type text not null default '',
  target_id text,
  ip_address inet,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
create index if not exists security_audit_logs_created_at on public.security_audit_logs(created_at desc);
create index if not exists security_audit_logs_actor on public.security_audit_logs(actor_user_id,created_at desc);


alter table public.app_sessions enable row level security;
alter table public.security_rate_limits enable row level security;
alter table public.security_audit_logs enable row level security;

create or replace function public.consume_security_rate_limit(p_bucket text, p_limit integer, p_window_seconds integer)
returns boolean language plpgsql security definer set search_path = public as $$
declare attempts_now integer; started timestamptz := clock_timestamp(); window_length interval;
begin
  if p_limit<1 or p_window_seconds<1 then raise exception 'Invalid rate limit settings.'; end if;
  window_length := make_interval(secs => p_window_seconds);
  insert into security_rate_limits(bucket,window_started_at,attempts) values(p_bucket,started,1)
  on conflict (bucket) do update set
    attempts=case when security_rate_limits.window_started_at <= started-window_length then 1 else security_rate_limits.attempts+1 end,
    window_started_at=case when security_rate_limits.window_started_at <= started-window_length then started else security_rate_limits.window_started_at end
  returning attempts into attempts_now;
  if random()<0.01 then delete from security_rate_limits where window_started_at < started-interval '1 day'; end if;
  return attempts_now<=p_limit;
end $$;
create or replace function public.clear_security_rate_limit(p_bucket text)
returns void language sql security definer set search_path = public as $$ delete from security_rate_limits where bucket=p_bucket $$;
create or replace function public.block_audit_mutation()
returns trigger language plpgsql set search_path = public as $$ begin raise exception 'Security audit records are append-only.'; return null; end $$;
drop trigger if exists security_audit_no_update_delete on public.security_audit_logs;
create trigger security_audit_no_update_delete before update or delete on public.security_audit_logs for each row execute function public.block_audit_mutation();
drop trigger if exists security_audit_no_truncate on public.security_audit_logs;
create trigger security_audit_no_truncate before truncate on public.security_audit_logs for each statement execute function public.block_audit_mutation();
revoke all on function public.consume_security_rate_limit(text,integer,integer) from public, anon, authenticated;
revoke all on function public.clear_security_rate_limit(text) from public, anon, authenticated;
grant execute on function public.consume_security_rate_limit(text,integer,integer) to service_role;
grant execute on function public.clear_security_rate_limit(text) to service_role;
grant select,insert,update,delete on public.app_sessions,public.security_rate_limits,public.security_audit_logs to service_role;
grant usage,select on sequence public.security_audit_logs_id_seq to service_role;

commit;
