begin;

-- Links an application role row to a Supabase Auth identity. Member rows remain
-- unchanged (NULL); only operator-provisioned administrators receive a link.
alter table public.users add column if not exists auth_user_id uuid;
create unique index if not exists users_auth_user_id_unique
  on public.users(auth_user_id) where auth_user_id is not null;
do $$ begin
  if not exists (select 1 from pg_constraint where conname = 'users_auth_user_id_admin_only' and conrelid = 'public.users'::regclass) then
    alter table public.users add constraint users_auth_user_id_admin_only
      check (auth_user_id is null or role = 'admin') not valid;
  end if;
end $$;
alter table public.users validate constraint users_auth_user_id_admin_only;
alter table public.users enable row level security;
revoke all on public.users from public, anon, authenticated;
grant select, insert, update, delete on public.users to service_role;
revoke all on sequence public.users_id_seq from public, anon, authenticated;
grant usage, select on sequence public.users_id_seq to service_role;

-- Preserve compatibility with installations that only applied the core schema.
create table if not exists public.admin_setup_tokens (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users(id) on delete cascade,
  token_hash text not null unique,
  expires_at timestamptz not null,
  used_at timestamptz,
  created_at timestamptz not null default now()
);
alter table public.admin_setup_tokens enable row level security;
revoke all on public.admin_setup_tokens from public, anon, authenticated;
grant select, insert, update, delete on public.admin_setup_tokens to service_role;
grant usage, select on sequence public.admin_setup_tokens_id_seq to service_role;

-- Remove legacy service-role functions that set the app's email_verified flag
-- from a custom token. Supabase Auth is now the sole source of admin email proof.
drop function if exists public.complete_library_admin_setup(text, text);
drop function if exists public.provision_library_admin(text, text, text, text, timestamptz);

-- Retiring admins revokes the app role and the Auth link. Auth users are kept;
-- ordinary member rows and their library data are never selected by this RPC.
create or replace function public.reset_library_admins(p_expected_user_ids bigint[], p_confirmation text)
returns table(user_id bigint, username text, email text)
language plpgsql security definer set search_path = pg_catalog, public as $$
declare reset_count integer; current_admin_ids bigint[];
begin
  if p_confirmation is distinct from 'RESET_LIBRARY_ADMINS' then
    raise exception 'Explicit reset confirmation is required.' using errcode = '22023';
  end if;
  if p_expected_user_ids is null then raise exception 'Expected administrator IDs are required.' using errcode = '22023'; end if;
  perform pg_advisory_xact_lock(74021, 1);
  lock table public.users, public.app_sessions, public.admin_setup_tokens,
    public.password_reset_tokens, public.email_verification_tokens in share row exclusive mode;
  select coalesce(array_agg(u.id order by u.id), array[]::bigint[]) into current_admin_ids from public.users u where u.role = 'admin';
  if current_admin_ids is distinct from p_expected_user_ids then
    raise exception 'Administrator accounts changed since the preview. Run the preview again.' using errcode = '40001';
  end if;
  select count(*)::integer into reset_count from public.users where role = 'admin';
  return query
  with targets as materialized (select u.id, u.username, u.email from public.users u where u.role = 'admin' for update),
  revoked as (
    update public.users u set role = 'user', is_active = false, auth_user_id = null,
      username = 'retired_admin_' || u.id::text || '_' || substr(md5(random()::text || clock_timestamp()::text || u.id::text), 1, 24),
      email = '', password_hash = 'disabled$' || md5(random()::text || clock_timestamp()::text || u.id::text),
      profile_photo = '', admin_mfa_secret = null, admin_mfa_enabled = false
    from targets t where u.id = t.id returning u.id, u.username, u.email
  ),
  sessions as (delete from public.app_sessions s using targets t where s.session_data ->> 'userId' = t.id::text or s.session_data ->> 'pendingMfaUserId' = t.id::text returning s.sid),
  setup_tokens as (update public.admin_setup_tokens t set used_at = clock_timestamp() from targets x where t.user_id = x.id and t.used_at is null returning t.id),
  password_tokens as (update public.password_reset_tokens t set used_at = clock_timestamp() from targets x where t.user_id = x.id and t.used_at is null returning t.id),
  verification_tokens as (update public.email_verification_tokens t set used_at = clock_timestamp() from targets x where t.user_id = x.id and t.used_at is null returning t.id)
  select r.id, r.username, r.email from revoked r;
  insert into public.security_audit_logs (actor_user_id, event, target_type, target_id, details)
  values (null, 'admin_accounts_reset', 'users', null, jsonb_build_object('account_count', reset_count, 'auth_accounts_deleted', false));
end;
$$;

revoke all on function public.reset_library_admins(bigint[],text) from public, anon, authenticated;
grant execute on function public.reset_library_admins(bigint[],text) to service_role;
commit;
