-- Apply this to an existing Supabase project before deploying the email
-- verification changes.
alter table public.users alter column email_verified set default false;

create table if not exists public.email_verification_tokens (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users(id) on delete cascade,
  token_hash text not null unique,
  expires_at timestamptz not null,
  used_at timestamptz,
  created_at timestamptz not null default now()
);
alter table public.email_verification_tokens enable row level security;
grant select, insert, update, delete on public.email_verification_tokens to service_role;
grant usage, select on sequence public.email_verification_tokens_id_seq to service_role;
