-- Private reader state for the existing authenticated read-only library.
-- Apply after schema.sql, security_hardening_migration.sql,
-- read_only_digital_migration.sql, and admin_features_migration.sql.
begin;

create table if not exists public.reader_favourites (
  user_id bigint not null references public.users(id) on delete cascade,
  book_id bigint not null references public.books(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (user_id, book_id)
);

create table if not exists public.reader_progress (
  user_id bigint not null references public.users(id) on delete cascade,
  book_id bigint not null references public.books(id) on delete cascade,
  location jsonb not null default '{"page":1}'::jsonb,
  updated_at timestamptz not null default now(),
  primary key (user_id, book_id)
);

create table if not exists public.reader_bookmarks (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users(id) on delete cascade,
  book_id bigint not null references public.books(id) on delete cascade,
  name text not null default '',
  location jsonb not null default '{"page":1}'::jsonb,
  created_at timestamptz not null default now()
);
create index if not exists reader_bookmarks_user_book_idx on public.reader_bookmarks(user_id, book_id, created_at desc);

create table if not exists public.reader_history (
  user_id bigint not null references public.users(id) on delete cascade,
  book_id bigint not null references public.books(id) on delete cascade,
  last_opened_at timestamptz not null default now(),
  open_count integer not null default 1 check (open_count > 0),
  last_page integer check (last_page is null or last_page > 0),
  primary key (user_id, book_id)
);
create index if not exists reader_history_recent_idx on public.reader_history(user_id, last_opened_at desc);

alter table public.reader_favourites enable row level security;
alter table public.reader_progress enable row level security;
alter table public.reader_bookmarks enable row level security;
alter table public.reader_history enable row level security;
grant select, insert, update, delete on public.reader_favourites, public.reader_progress, public.reader_bookmarks, public.reader_history to service_role;
grant usage, select on sequence public.reader_bookmarks_id_seq to service_role;

commit;
