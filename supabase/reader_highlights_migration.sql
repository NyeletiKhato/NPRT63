-- Private, per-reader text highlights for digital books.
begin;

create table if not exists public.reader_highlights (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users(id) on delete cascade,
  book_id bigint not null references public.books(id) on delete cascade,
  page integer not null check (page > 0),
  start_offset integer not null check (start_offset >= 0),
  end_offset integer not null check (end_offset > start_offset),
  quote text not null check (char_length(quote) between 1 and 2000),
  color text not null check (color in ('yellow', 'green', 'blue', 'pink')),
  created_at timestamptz not null default now()
);

create index if not exists reader_highlights_user_book_idx
  on public.reader_highlights(user_id, book_id, page, start_offset);

alter table public.reader_highlights enable row level security;
grant select, insert, update, delete on public.reader_highlights to service_role;
grant usage, select on sequence public.reader_highlights_id_seq to service_role;

commit;
