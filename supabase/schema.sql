create table if not exists public.users (
  id bigint generated by default as identity primary key,
  username text not null unique,
  email text not null default '',
  password_hash text not null,
  role text not null default 'user' check (role in ('admin', 'user')),
  is_active boolean not null default true,
  email_verified boolean not null default false,
  profile_photo text not null default '',
  admin_mfa_secret text,
  admin_mfa_enabled boolean not null default false,
  created_at timestamptz not null default now()
);
-- Django allowed repeated email addresses; username is the account identifier.
drop index if exists public.users_email_unique;
alter table public.users alter column email_verified set default false;

create table if not exists public.books (
  id bigint generated by default as identity primary key,
  title text not null,
  author text not null,
  isbn text not null unique,
  category text not null,
  quantity integer not null default 1 check (quantity >= 0),
  available_copies integer not null default 1 check (available_copies >= 0),
  virtual_file_path text not null default '',
  virtual_file_name text not null default '',
  virtual_file_type text not null default '',
  constraint books_available_not_over_quantity check (available_copies <= quantity)
);
create table if not exists public.borrow_records (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users(id) on delete cascade,
  book_id bigint not null references public.books(id) on delete cascade,
  borrow_date date not null,
  due_date date not null,
  return_date date,
  collected_at timestamptz,
  book_format text not null default 'physical' check (book_format in ('physical','virtual')),
  status text not null default 'borrowed' check (status in ('pending_approval','borrowed','returned','overdue','rejected')),
  return_requested_at timestamptz,
  stock_reserved boolean not null default false
);
create table if not exists public.login_activities (
  id bigint generated by default as identity primary key,
