-- Run this file in the Supabase SQL Editor before starting the application.
-- The Node server uses the service role key and enforces role checks in its API.
create extension if not exists pgcrypto;

create table if not exists public.users (
  id bigint generated by default as identity primary key,
  username text not null unique,
  email text not null default '',
  password_hash text not null,
  role text not null default 'user' check (role in ('admin', 'user')),
  is_active boolean not null default true,
  email_verified boolean not null default false,
  profile_photo text not null default '',
  admin_mfa_secret text,
  admin_mfa_enabled boolean not null default false,
  created_at timestamptz not null default now()
);
-- Usernames are the unique account identifiers; email addresses may be shared.
drop index if exists public.users_email_unique;
alter table public.users alter column email_verified set default false;

create table if not exists public.books (
  id bigint generated by default as identity primary key,
  title text not null,
  author text not null,
  isbn text not null unique,
  category text not null,
  virtual_file_path text not null default '',
  virtual_file_name text not null default '',
  virtual_file_type text not null default ''
);
create table if not exists public.login_activities (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users(id) on delete cascade,
  logged_in_at timestamptz not null default now()
);
create table if not exists public.password_reset_tokens (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users(id) on delete cascade,
  token_hash text not null,
  expires_at timestamptz not null,
  used_at timestamptz,
  created_at timestamptz not null default now()
);
create table if not exists public.email_verification_tokens (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users(id) on delete cascade,
  token_hash text not null unique,
  expires_at timestamptz not null,
  used_at timestamptz,
  created_at timestamptz not null default now()
);
create table if not exists public.newsletter_subscriptions (
  id bigint generated by default as identity primary key,
  email text not null unique,
  subscribed_at timestamptz not null default now()
);


create table if not exists public.app_sessions (
  sid text primary key,
  session_data jsonb not null,
  expires_at timestamptz not null
);
create index if not exists app_sessions_expires_at on public.app_sessions(expires_at);
create table if not exists public.security_rate_limits (
  bucket text primary key,
  window_started_at timestamptz not null,
  attempts integer not null default 0
);
create table if not exists public.security_audit_logs (
  id bigint generated by default as identity primary key,
  actor_user_id bigint,
  event text not null,
  target_type text not null default '',
  target_id text,
  ip_address inet,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
create index if not exists security_audit_logs_created_at on public.security_audit_logs(created_at desc);
create index if not exists security_audit_logs_actor on public.security_audit_logs(actor_user_id,created_at desc);

