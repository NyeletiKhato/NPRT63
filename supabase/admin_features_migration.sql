-- Additive admin features for the existing read-only library.
-- Run in the Supabase SQL Editor after schema.sql and earlier migrations.
begin;

create table if not exists public.categories (
  id bigint generated by default as identity primary key,
  name text not null unique,
  description text not null default '',
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.authors (
  id bigint generated by default as identity primary key,
  name text not null unique,
  biography text not null default '',
  created_at timestamptz not null default now()
);

insert into public.categories(name)
select distinct trim(category) from public.books where nullif(trim(category),'') is not null
on conflict (name) do nothing;
insert into public.authors(name)
select distinct trim(author) from public.books where nullif(trim(author),'') is not null
on conflict (name) do nothing;

alter table public.books
  add column if not exists description text not null default '',
  add column if not exists created_at timestamptz not null default now(),
  add column if not exists publication_year integer,
  add column if not exists publisher text not null default '',
  add column if not exists language text not null default '',
  add column if not exists tags text[] not null default '{}',
  add column if not exists is_featured boolean not null default false,
  add column if not exists status text not null default 'published',
  add column if not exists cover_path text not null default '',
  add column if not exists cover_type text not null default '',
  add column if not exists cover_size bigint not null default 0,
  add column if not exists file_size bigint not null default 0,
  add column if not exists validated_at timestamptz,
  add column if not exists category_id bigint references public.categories(id) on delete set null,
  add column if not exists author_id bigint references public.authors(id) on delete set null;

-- ISBN is optional for digital titles. Keep uniqueness only for supplied ISBNs.
alter table public.books alter column isbn drop not null;
alter table public.books drop constraint if exists books_isbn_key;
update public.books set isbn = null where trim(coalesce(isbn, '')) = '';
create unique index if not exists books_isbn_unique_nonempty_idx
  on public.books(isbn) where isbn is not null and trim(isbn) <> '';

update public.books b set category_id=c.id from public.categories c where b.category_id is null and lower(trim(b.category))=lower(c.name);
update public.books b set author_id=a.id from public.authors a where b.author_id is null and lower(trim(b.author))=lower(a.name);

create table if not exists public.book_authors (
  book_id bigint not null references public.books(id) on delete cascade,
  author_id bigint not null references public.authors(id) on delete restrict,
  position integer not null default 0,
  primary key (book_id,author_id)
);
insert into public.book_authors(book_id,author_id)
select id,author_id from public.books where author_id is not null
on conflict (book_id,author_id) do nothing;

alter table public.books drop constraint if exists books_status_check;
alter table public.books add constraint books_status_check check (status in ('draft','published','archived'));
alter table public.books drop constraint if exists books_publication_year_check;
alter table public.books add constraint books_publication_year_check check (publication_year is null or publication_year between 1000 and 3000);
create index if not exists books_status_title_idx on public.books(status, title);
create index if not exists books_category_id_idx on public.books(category_id);
create index if not exists books_author_id_idx on public.books(author_id);
create index if not exists books_featured_idx on public.books(is_featured) where is_featured;

create table if not exists public.book_open_events (
  id bigint generated by default as identity primary key,
  book_id bigint not null references public.books(id) on delete cascade,
  user_id bigint not null references public.users(id) on delete cascade,
  opened_at timestamptz not null default now()
);
create index if not exists book_open_events_opened_at_idx on public.book_open_events(opened_at desc);
create index if not exists book_open_events_book_idx on public.book_open_events(book_id, opened_at desc);
create index if not exists book_open_events_user_idx on public.book_open_events(user_id, opened_at desc);

create table if not exists public.library_settings (
  setting_key text primary key,
  setting_value jsonb not null default '{}'::jsonb,
  updated_by bigint references public.users(id) on delete set null,
  updated_at timestamptz not null default now()
);
insert into public.library_settings(setting_key, setting_value) values
 ('branding', '{"name":"Community Digital Library","contact_email":"","contact_phone":"","logo_url":""}'::jsonb),
 ('catalogue', '{"registration_enabled":true,"featured_book_ids":[]}'::jsonb)
on conflict (setting_key) do nothing;

alter table public.categories enable row level security;
alter table public.authors enable row level security;
alter table public.book_authors enable row level security;
alter table public.book_open_events enable row level security;
alter table public.library_settings enable row level security;

grant select, insert, update, delete on public.categories, public.authors, public.book_authors, public.book_open_events, public.library_settings to service_role;
grant usage, select on sequence public.categories_id_seq, public.authors_id_seq, public.book_open_events_id_seq to service_role;
grant select, insert, update, delete on public.books to service_role;
grant usage, select on sequence public.books_id_seq to service_role;

create or replace function public.admin_library_analytics(p_since timestamptz)
returns jsonb language sql security invoker set search_path = public as $$
  with book_counts as (
    select count(*)::int as total, count(*) filter (where status='published')::int as published,
           count(*) filter (where status='draft')::int as drafts,
           count(*) filter (where status='archived')::int as archived,
           count(*) filter (where coalesce(virtual_file_path,'') <> '')::int as with_file,
           count(*) filter (where coalesce(cover_path,'') = '')::int as missing_cover,
           count(*) filter (where coalesce(description,'') = '' or coalesce(language,'') = '')::int as incomplete_metadata,
           coalesce(sum(file_size),0)::bigint as file_bytes
    from books
  ), users_counts as (
    select count(*) filter (where role='user')::int as readers,
           count(*) filter (where role='user' and is_active)::int as active_readers,
           count(*) filter (where role='user' and not is_active)::int as deactivated_readers,
           count(*) filter (where role='user' and created_at >= p_since)::int as registrations
    from users
  ), open_counts as (
    select count(*)::int as opens, count(distinct user_id)::int as unique_readers
    from book_open_events where opened_at >= p_since
  ), most_read as (
    select coalesce(jsonb_agg(to_jsonb(t)), '[]'::jsonb) as rows from (
      select b.id,b.title,count(e.id)::int as opens from books b join book_open_events e on e.book_id=b.id
      where e.opened_at >= p_since group by b.id,b.title order by count(e.id) desc,b.title limit 10
    ) t
  ), daily as (
    select coalesce(jsonb_agg(to_jsonb(t) order by t.day), '[]'::jsonb) as rows from (
      select date_trunc('day',opened_at)::date as day,count(*)::int as opens,count(distinct user_id)::int as readers
      from book_open_events where opened_at >= p_since group by 1
    ) t
  ), categories_ranked as (
    select coalesce(jsonb_agg(to_jsonb(t)), '[]'::jsonb) as rows from (
      select coalesce(nullif(b.category,''),'Uncategorised') as category,count(e.id)::int as opens
      from book_open_events e join books b on b.id=e.book_id where e.opened_at >= p_since
      group by 1 order by count(e.id) desc limit 10
    ) t
  )
  select jsonb_build_object(
    'books',(select to_jsonb(book_counts) from book_counts),
    'readers',(select to_jsonb(users_counts) from users_counts),
    'activity',(select to_jsonb(open_counts) from open_counts),
    'most_read',(select rows from most_read),'daily',(select rows from daily),'popular_categories',(select rows from categories_ranked)
  );
$$;
revoke all on function public.admin_library_analytics(timestamptz) from public, anon, authenticated;
grant execute on function public.admin_library_analytics(timestamptz) to service_role;

